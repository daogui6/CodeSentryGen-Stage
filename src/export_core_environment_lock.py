from __future__ import annotations

import argparse
import json
import platform
import sys
from importlib import metadata
from pathlib import Path
from typing import Any

from packaging.markers import default_environment
from packaging.requirements import InvalidRequirement, Requirement
from packaging.utils import canonicalize_name


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CONTRACT = ROOT / "config/core_runtime_environment_v1.json"
DEFAULT_OUT = (
    ROOT / "output/f11_reproducibility/core_environment_lock.txt"
)
DEFAULT_REPORT = (
    ROOT / "output/f11_reproducibility/core_environment_report.json"
)


def read_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"Expected JSON object: {path}")
    return value


def active_direct_roots(contract: dict[str, Any]) -> list[str]:
    env = default_environment()
    env["extra"] = ""
    roots: list[str] = []

    for row in contract.get("direct_dependencies", []):
        if not isinstance(row, dict):
            continue
        name = str(row.get("distribution") or "").strip()
        if not name:
            continue

        marker_text = str(row.get("marker") or "").strip()
        if marker_text:
            requirement = Requirement(f"{name}; {marker_text}")
            if requirement.marker is not None and not requirement.marker.evaluate(env):
                continue
        roots.append(name)

    return roots


def installed_dependency_closure(
    roots: list[str],
) -> tuple[dict[str, str], list[str]]:
    env = default_environment()
    env["extra"] = ""
    queue = list(roots)
    seen: set[str] = set()
    versions: dict[str, str] = {}
    missing: list[str] = []

    while queue:
        requested = queue.pop(0)
        canonical = canonicalize_name(requested)
        if canonical in seen:
            continue
        seen.add(canonical)

        try:
            dist = metadata.distribution(requested)
        except metadata.PackageNotFoundError:
            missing.append(requested)
            continue

        dist_name = str(dist.metadata.get("Name") or requested).strip()
        versions[canonicalize_name(dist_name)] = (
            f"{dist_name}=={dist.version}"
        )

        for raw in dist.requires or []:
            try:
                req = Requirement(raw)
            except InvalidRequirement:
                continue
            if req.marker is not None and not req.marker.evaluate(env):
                continue
            dep = str(req.name).strip()
            if dep and canonicalize_name(dep) not in seen:
                queue.append(dep)

    return versions, sorted(set(missing), key=str.lower)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Capture the exact installed dependency closure for the "
            "CodeSentry-Gen repaired core. This is F-11 evidence and does "
            "not modify the tracked lock automatically."
        )
    )
    parser.add_argument("--contract", type=Path, default=DEFAULT_CONTRACT)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    return parser.parse_args()


def resolve(path: Path) -> Path:
    return path if path.is_absolute() else ROOT / path


def main() -> None:
    args = parse_args()
    contract_path = resolve(args.contract)
    out_path = resolve(args.out)
    report_path = resolve(args.report)
    contract = read_json(contract_path)

    expected_minor = str(
        contract.get("python", {}).get("required_major_minor") or ""
    ).strip()
    actual_minor = f"{sys.version_info.major}.{sys.version_info.minor}"
    if actual_minor != expected_minor:
        raise SystemExit(
            "F-11 environment capture refused: "
            f"expected Python {expected_minor}.x, got {sys.version.split()[0]}"
        )

    roots = active_direct_roots(contract)
    pins, missing = installed_dependency_closure(roots)
    if missing:
        raise SystemExit(
            "F-11 environment capture refused; missing distributions: "
            + ", ".join(missing)
        )

    out_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "# CodeSentry-Gen repaired-core dependency closure",
        "# Generated by src/export_core_environment_lock.py",
        f"# Python {sys.version.split()[0]} ({platform.python_implementation()})",
        "# Promote to requirements-core-lock.txt only after smoke/regression validation.",
        "",
    ]
    lines.extend(pins[key] for key in sorted(pins))
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    report = {
        "schema_version": "codesentry_gen_core_environment_capture_v1",
        "status": "CAPTURED_NOT_YET_FROZEN",
        "python": {
            "implementation": platform.python_implementation(),
            "version": sys.version.split()[0],
            "major_minor": actual_minor,
        },
        "contract_file": str(contract_path.relative_to(ROOT)).replace("\\", "/"),
        "direct_roots": roots,
        "package_count": len(pins),
        "pins": [pins[key] for key in sorted(pins)],
        "missing": missing,
        "lock_evidence_file": str(out_path.relative_to(ROOT)).replace("\\", "/"),
        "scientific_boundary": {
            "capture_is_not_final_freeze": True,
            "formal_step9_started": False,
        },
    }
    report_path.write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )

    print("F-11 CORE ENVIRONMENT CAPTURE PASS")
    print(f"python = {sys.version.split()[0]}")
    print(f"direct_roots = {len(roots)}")
    print(f"package_count = {len(pins)}")
    print(f"lock = {out_path.relative_to(ROOT)}")
    print(f"report = {report_path.relative_to(ROOT)}")
    print("formal_step9_started = false")


if __name__ == "__main__":
    main()
